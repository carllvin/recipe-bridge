let LANG_CODE = 'en';
let T = TRANSLATIONS.en;
let APP_CONFIG = {};

function t(key) {
  const text = (T && T[key] !== undefined) ? T[key] : ((TRANSLATIONS.en[key] !== undefined) ? TRANSLATIONS.en[key] : key);
  // With Mealie (RECIPE_MANAGER=mealie) "Tandoor" in the texts means the
  // recipe manager.
  const manager = APP_CONFIG.recipe_manager;
  return manager && manager !== 'Tandoor' && typeof text === 'string'
    ? text.replace(/Tandoor/g, manager) : text;
}

function tf(key, params) {
  let str = t(key);
  Object.keys(params || {}).forEach((k) => {
    str = str.split(`{${k}}`).join(params[k]);
  });
  return str;
}

function applyStaticTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((elm) => {
    const key = elm.getAttribute('data-i18n');
    elm.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((elm) => {
    elm.title = t(elm.getAttribute('data-i18n-title'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((elm) => {
    const key = elm.getAttribute('data-i18n-placeholder');
    elm.setAttribute('placeholder', t(key));
  });
}

async function initI18n() {
  try {
    const res = await fetch('/api/config');
    const data = await res.json();
    LANG_CODE = data.language_code || 'en';
    APP_CONFIG = data;
  } catch {
    LANG_CODE = 'en';
  }
  T = TRANSLATIONS[LANG_CODE] || TRANSLATIONS.en;
  document.documentElement.setAttribute('lang', LANG_CODE);
  applyStaticTranslations();
}
